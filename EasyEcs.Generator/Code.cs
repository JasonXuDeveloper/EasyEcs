using System;
using System.Linq;

namespace EasyEcs.Generator;

/// <summary>Tiny helpers for arity templates: Code.List(3, i => $"T{i}") == "T1, T2, T3".</summary>
internal static class Code
{
    public static string List(int n, Func<int, string> item, string separator = ", ") =>
        string.Join(separator, Enumerable.Range(1, n).Select(item));

    public static string Lines(int n, Func<int, string> item) => List(n, item, "\n");

    public static string TypeParams(int n) => List(n, i => $"T{i}");

    public static string Constraints(int n, string indent) =>
        Lines(n, i => $"{indent}where T{i} : struct, IComponent");

    public const string Header = "// <auto-generated/>\n#nullable disable\n";
}
