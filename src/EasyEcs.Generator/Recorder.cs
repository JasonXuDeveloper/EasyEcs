using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;
using Microsoft.CodeAnalysis.Text;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace EasyEcs.Generator;

/// <summary>
/// What this assembly's generator records for the generators of the assemblies that reference it (Recorded.cs reads it
/// back): per public constructor of a public struct, the member each parameter sets (<c>[assembly: ConstructorFields]</c>,
/// or the reason they are not known), and per small public helper (a static method, a member of a struct, a property's
/// accessor with a body), its body with every name qualified (<c>[assembly: InlineBody]</c>, or the reason it cannot
/// be inlined). A field the referencing assembly cannot see becomes a placeholder (<c>__EasyEcsAccessor{i}</c>,
/// <c>kind|type|name</c>), an internal static helper it calls a local function of its own (<c>__EasyEcsHelper{j}</c>).
/// Only members taking and returning values (a vector loop inlines nothing else) are recorded. Source output, one file
/// per source file: an IDE compiling a ProjectReference sees what a build sees, and an
/// edit rebinds only the bodies of the file it touched, which the syntax filters first (size, loops, throws).
/// </summary>
internal static class Recorder
{
    /// <summary>The largest body recorded, in characters of source: a helper the call inliner takes is small.</summary>
    private const int MaxBody = 2048;

    /// <summary>How deep internal helpers calling internal helpers are recorded.</summary>
    private const int MaxHelpers = 4;

    /// <summary>One source file's facts: the generated file's name and the attribute lines.</summary>
    private sealed record Facts(string HintName, EquatableArray<string> Lines);

    public static void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // One stage entry and one generated file per source file, not per type: the driver's work per run grows with
        // the entries and files it carries over, and an edit rereads only the file it touched either way.
        var facts = context.SyntaxProvider
            .CreateSyntaxProvider(static (node, _) => node is CompilationUnitSyntax, static (ctx, ct) => Read(ctx, ct))
            .Where(static f => f is not null)
            .WithTrackingName("RecordedTypes");
        context.RegisterSourceOutput(facts, static (spc, facts) =>
        {
            var sb = new StringBuilder("// <auto-generated/>\n// What EasyEcs's generator recorded for the assemblies that reference this one.\n\n");
            foreach (var line in facts!.Lines) sb.Append(line).Append('\n');
            spc.AddSource(facts.HintName, SourceText.From(sb.ToString(), Encoding.UTF8));
        });
    }

    /// <summary>
    /// A public struct, class or record outside any non-public type: the only ones whose members another assembly calls
    /// (a ref struct is no component, and its members take no part in a vector loop).
    /// </summary>
    private static bool IsCandidate(SyntaxNode node)
    {
        if (node is not (StructDeclarationSyntax or ClassDeclarationSyntax or RecordDeclarationSyntax)
            || ((TypeDeclarationSyntax)node).Modifiers.Any(SyntaxKind.RefKeyword))
            return false;
        for (var n = node; n is TypeDeclarationSyntax type; n = n.Parent)
            if (!type.Modifiers.Any(SyntaxKind.PublicKeyword)) return false;
        return true;
    }

    /// <summary>The facts of every public type declared in one source file, or null when it declares none to record.</summary>
    private static Facts? Read(GeneratorSyntaxContext ctx, System.Threading.CancellationToken ct)
    {
        var model = ctx.SemanticModel;
        if (model.Compilation.GetTypeByMetadataName(Recorded.InlineBodyAttribute) is not { } attribute // an EasyEcs without them
            || SymbolEqualityComparer.Default.Equals(attribute.ContainingAssembly, model.Compilation.Assembly)) // EasyEcs itself: its API is not inlined
            return null;
        var lines = new List<string>();
        string? hint = null;
        // Types sit in namespaces and other types, never in bodies: the walk stops at members.
        foreach (var node in ctx.Node.DescendantNodes(static n => n is CompilationUnitSyntax or BaseNamespaceDeclarationSyntax or TypeDeclarationSyntax))
        {
            ct.ThrowIfCancellationRequested();
            if (node is not TypeDeclarationSyntax declaration || !IsCandidate(declaration)) continue;
            int before = lines.Count;
            if (model.GetDeclaredSymbol(declaration, ct) is INamedTypeSymbol type && Visible(type)) Read(declaration, type, model.Compilation, lines, ct);
            if (hint == null && lines.Count > before) hint = HintName(declaration, model.GetDeclaredSymbol(declaration, ct)!, ct);
        }

        return hint == null ? null : new Facts(hint, new EquatableArray<string>(lines.ToArray()));
    }

    /// <summary>The generated file's name: the first type recorded, numbered by its declaration when it is partial.</summary>
    private static string HintName(TypeDeclarationSyntax node, ISymbol type, System.Threading.CancellationToken ct)
    {
        int index = type.DeclaringSyntaxReferences.Select(r => r.GetSyntax(ct)).ToList().IndexOf(node);
        string hint = type.ToDisplayString(Symbols.Fqn).Replace("global::", "").Replace('<', '[').Replace('>', ']');
        return $"{hint}{(index > 0 ? "." + index : "")}.Recorded.g.cs";
    }

    /// <summary>
    /// Whether a vector loop could take <paramref name="type"/> as a value: helpers taking or returning anything else
    /// (a World, a string, an array) are never inlined into one, so they are not recorded.
    /// </summary>
    private static bool LaneType(ITypeSymbol type) => type.SpecialType == SpecialType.System_Void || type.IsValueType && !type.IsRefLikeType;

    /// <summary>The facts of one type declaration, added to <paramref name="lines"/>.</summary>
    private static void Read(TypeDeclarationSyntax node, INamedTypeSymbol type, Compilation compilation, List<string> lines, System.Threading.CancellationToken ct)
    {
        if (type.IsValueType)
            foreach (var constructor in type.InstanceConstructors)
                if (constructor.DeclaredAccessibility == Accessibility.Public && !constructor.IsImplicitlyDeclared && constructor.Parameters.All(p => LaneType(p.Type))
                    && Declares(node, constructor, ct))
                    lines.Add(Constructor(constructor, compilation, ct));
        if (!IsGenericAnywhere(type))
            foreach (var member in type.GetMembers())
            {
                if (member is IMethodSymbol { MethodKind: MethodKind.Ordinary } method) Add(method, null);
                else if (member is IPropertySymbol { IsIndexer: false } property)
                {
                    Add(property.GetMethod, property);
                    if (property.SetMethod is { IsInitOnly: false } set) Add(set, property);
                }
            }

        void Add(IMethodSymbol? method, IPropertySymbol? property)
        {
            if (method == null || method.DeclaredAccessibility != Accessibility.Public || (property ?? (ISymbol)method).DeclaredAccessibility != Accessibility.Public
                || method.IsAbstract || method.IsVirtual || method.IsOverride || method.IsExtern || method.IsGenericMethod || method.ReturnsByRef || method.ReturnsByRefReadonly
                || !method.IsStatic && !type.IsValueType || type.IsExtension || Symbols.IsGenerated(method) || method.Parameters.Any(p => p.IsParams)
                || !LaneType(method.ReturnType) || method.Parameters.Any(p => !LaneType(p.Type)))
                return;
            var syntax = method.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax(ct);
            if (syntax == null || !node.Span.Contains(syntax.Span)) return;
            SyntaxNode? body = syntax switch
            {
                MethodDeclarationSyntax m => (SyntaxNode?)m.Body ?? m.ExpressionBody?.Expression,
                AccessorDeclarationSyntax a => (SyntaxNode?)a.Body ?? a.ExpressionBody?.Expression,
                ArrowExpressionClauseSyntax arrow => arrow.Expression,
                _ => null,
            };
            if (body == null || body.Span.Length > MaxBody) return; // an auto-property, or no small helper: nothing to say
            string id = method.GetDocumentationCommentId() ?? "";
            if (id.Length == 0) return;
            string? reason = Kernel.BodyRefusal(body);
            if (reason == null)
            {
                try
                {
                    var writer = new Writer(compilation, ct);
                    string text = writer.Record(method, body);
                    lines.Add($"[assembly: global::EasyEcs.InlineBody({Literal(id)}, {Literal(text)}{string.Concat(writer.Accessors.Select(a => ", " + Literal(a)))})]");
                    return;
                }
                catch (NotRecorded why)
                {
                    reason = why.Message;
                }
                catch (System.Exception e) when (e is not System.OperationCanceledException)
                {
                    reason = Kernel.FailedTo("record", e);
                }
            }

            lines.Add($"[assembly: global::EasyEcs.InlineBody({Literal(id)}, \"\", Reason = {Literal(reason)})]");
        }
    }

    /// <summary>Whether <paramref name="member"/> is declared in this declaration of its type (a partial type has several).</summary>
    private static bool Declares(TypeDeclarationSyntax node, ISymbol member, System.Threading.CancellationToken ct) =>
        member.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax(ct) is { } syntax && (syntax == node || syntax.Parent == node);

    private static string Constructor(IMethodSymbol constructor, Compilation compilation, System.Threading.CancellationToken ct)
    {
        string id = Literal(constructor.GetDocumentationCommentId() ?? "");
        string? reason;
        try
        {
            var (members, why) = Recorded.Assignments(constructor, compilation, ct);
            if (members != null) return $"[assembly: global::EasyEcs.ConstructorFields({id}{string.Concat(members.Select(m => ", " + Literal(m?.Name ?? "")))})]";
            reason = why;
        }
        catch (System.Exception e) when (e is not System.OperationCanceledException)
        {
            reason = Kernel.FailedTo("record", e);
        }

        return $"[assembly: global::EasyEcs.ConstructorFields({id}, Reason = {Literal(reason ?? "")})]";
    }

    private static string Literal(string text) => SymbolDisplay.FormatLiteral(text, true);

    private static bool IsGenericAnywhere(INamedTypeSymbol type)
    {
        for (var t = type; t != null; t = t.ContainingType)
            if (t.TypeParameters.Length > 0) return true;
        return false;
    }

    /// <summary>Whether code of another assembly reaches <paramref name="symbol"/>: it and every type around it are public.</summary>
    internal static bool Visible(ISymbol symbol)
    {
        for (var s = symbol; s != null && s is not INamespaceSymbol; s = s.ContainingSymbol)
            if (s.DeclaredAccessibility != Accessibility.Public) return false;
        return true;
    }

    /// <summary>Whether another assembly can name <paramref name="type"/> (its elements and type arguments too).</summary>
    private static bool VisibleType(ITypeSymbol? type) => type switch
    {
        null => false,
        IArrayTypeSymbol array => VisibleType(array.ElementType),
        IPointerTypeSymbol pointer => VisibleType(pointer.PointedAtType),
        ITypeParameterSymbol => true,
        INamedTypeSymbol named => (named.SpecialType != SpecialType.None || named.IsTupleType || Visible(named)) && named.TypeArguments.All(VisibleType),
        _ => true,
    };

    /// <summary>The metadata name <c>[UnsafeAccessorType]</c> takes: <c>Game.Physics</c>, a nested type <c>Game.Outer+Inner</c>.</summary>
    private static string MetadataName(INamedTypeSymbol type) =>
        (type.ContainingType is { } outer ? MetadataName(outer) + "+"
            : type.ContainingNamespace is { IsGlobalNamespace: false } ns ? ns.ToDisplayString() + "." : "") + type.MetadataName;

    private sealed class NotRecorded(string reason) : System.Exception(reason);

    /// <summary>
    /// Writes a member's body as the static local functions <see cref="Recorded"/> describes: names qualified, constants
    /// as their values, <c>this</c> as the parameter <c>@this</c>, hidden fields as placeholders, hidden static helpers
    /// as local functions of their own; anything else hidden fails with the reason.
    /// </summary>
    private sealed class Writer(Compilation compilation, System.Threading.CancellationToken ct)
    {
        /// <summary>The placeholders' fields, in order: <c>kind|type|name</c>.</summary>
        public readonly List<string> Accessors = new();
        private readonly List<string> _placeholders = new();
        private readonly Dictionary<string, string> _byField = new(System.StringComparer.Ordinal);
        private readonly List<string> _helpers = new();
        private readonly Dictionary<IMethodSymbol, string> _helperNames = new(SymbolEqualityComparer.Default);

        public string Record(IMethodSymbol method, SyntaxNode body)
        {
            string main = Function(method, body, Recorded.Body);
            return main + string.Concat(_helpers) + string.Concat(_placeholders);
        }

        /// <summary>The member (or a helper) as a static local function named <paramref name="name"/>.</summary>
        private string Function(IMethodSymbol method, SyntaxNode body, string name)
        {
            var model = compilation.GetSemanticModel(body.SyntaxTree);
            if (!VisibleType(method.ReturnType) && !method.ReturnsVoid) throw new NotRecorded($"it returns {method.ReturnType.Name}, which other assemblies cannot name");
            var parameters = new List<string>();
            if (!method.IsStatic)
            {
                bool writes = model.GetOperation(body, ct)?.DescendantsAndSelf().OfType<IInstanceReferenceOperation>().Any(Uses.MayWrite) ?? true;
                parameters.Add($"{(writes ? "ref" : "in")} {method.ContainingType.ToDisplayString(Symbols.Fqn)} @this");
            }
            foreach (var p in method.Parameters)
            {
                if (!VisibleType(p.Type)) throw new NotRecorded($"its parameter '{p.Name}' is of a type other assemblies cannot name");
                string modifier = p.RefKind switch { RefKind.Ref => "ref ", RefKind.Out => "out ", RefKind.In => "in ", RefKind.RefReadOnlyParameter => "ref readonly ", _ => "" };
                parameters.Add($"{modifier}{p.Type.ToDisplayString(Symbols.Fqn)} @{p.Name}");
            }

            var rewritten = new Rewriter(this, model, method, ct).Visit(body)!;
            string returns = method.ReturnsVoid ? "void" : method.ReturnType.ToDisplayString(Symbols.Fqn);
            string text = rewritten is BlockSyntax ? Compact(rewritten) : "=>" + Compact(rewritten) + ";";
            return $"static {returns} {name}({string.Join(",", parameters)}){text}";
        }

        /// <summary>The placeholder of a hidden field, in the form the use needs (read through <c>in</c>, written through <c>ref</c>, static).</summary>
        public string Placeholder(IFieldSymbol field, bool write)
        {
            if (!VisibleType(field.Type)) throw new NotRecorded($"it reads field {field.Name}, whose type other assemblies cannot name");
            if (field.ContainingType is not { } owner || IsGenericAnywhere(owner) || owner.IsRefLikeType) throw new NotRecorded($"it reads field {field.Name} of a type other assemblies cannot reach");
            if (!field.IsStatic && (!owner.IsValueType || !Visible(owner))) throw new NotRecorded($"it reads field {field.Name} of {owner.Name}, which other assemblies cannot reach");
            if (field.IsStatic && field.IsVolatile || field.IsFixedSizeBuffer) throw new NotRecorded($"it reads field {field.Name} of {owner.Name}, which other assemblies cannot reach");
            string kind = !field.IsStatic ? "field" : field.IsReadOnly ? "static readonly field" : "static field";
            string form = field.IsStatic ? "s" : write ? "w" : "r";
            string key = $"{form}|{kind}|{MetadataName(owner)}|{field.Name}";
            if (_byField.TryGetValue(key, out var known)) return known;
            string name = Recorded.Accessor + Accessors.Count;
            Accessors.Add($"{kind}|{MetadataName(owner)}|{field.Name}");
            string type = field.Type.ToDisplayString(Symbols.Fqn);
            _placeholders.Add(field.IsStatic ? $"static ref {type} {name}()=>throw null;"
                : write ? $"static ref {type} {name}(ref {owner.ToDisplayString(Symbols.Fqn)} o)=>throw null;"
                : $"static ref readonly {type} {name}(in {owner.ToDisplayString(Symbols.Fqn)} o)=>throw null;");
            return _byField[key] = name;
        }

        /// <summary>The local function standing for a hidden static helper the body calls (its own body recorded too).</summary>
        public string Helper(IMethodSymbol method)
        {
            if (_helperNames.TryGetValue(method, out var known)) return known;
            if (method.IsGenericMethod || IsGenericAnywhere(method.ContainingType) || method.IsExtern || method.IsAbstract || method.ReturnsByRef || method.ReturnsByRefReadonly
                || method.Parameters.Any(p => p.IsParams))
                throw new NotRecorded($"it calls {method.ContainingType.Name}.{method.Name}, which other assemblies cannot reach");
            if (_helperNames.Count >= MaxHelpers) throw new NotRecorded($"it calls more than {MaxHelpers} internal helpers");
            var syntax = method.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax(ct);
            SyntaxNode? body = syntax switch
            {
                MethodDeclarationSyntax m => (SyntaxNode?)m.Body ?? m.ExpressionBody?.Expression,
                _ => null,
            };
            if (body == null || body.Span.Length > MaxBody || Kernel.BodyRefusal(body) is { } refused)
                throw new NotRecorded($"it calls {method.ContainingType.Name}.{method.Name}, which other assemblies cannot reach and the generator does not record");
            string name = Recorded.Helper + _helperNames.Count;
            _helperNames[method] = name;
            _helpers.Add(Function(method, body, name));
            return name;
        }
    }

    /// <summary>One body's names rewritten (<see cref="Writer"/>).</summary>
    private sealed class Rewriter(Writer writer, SemanticModel model, IMethodSymbol member, System.Threading.CancellationToken ct) : CSharpSyntaxRewriter
    {
        private System.Threading.CancellationToken Ct => ct;

        private ISymbol? Bound(SyntaxNode node) => model.GetSymbolInfo(node, Ct).Symbol;

        public override SyntaxNode? VisitThisExpression(ThisExpressionSyntax node) => IdentifierName("@this").WithTriviaFrom(node);

        public override SyntaxNode? VisitBaseExpression(BaseExpressionSyntax node) => throw new NotRecorded("it uses 'base'");

        public override SyntaxNode? VisitMemberAccessExpression(MemberAccessExpressionSyntax node)
        {
            if (!node.IsKind(SyntaxKind.SimpleMemberAccessExpression)) return base.VisitMemberAccessExpression(node);
            var symbol = Bound(node);
            if (symbol is IFieldSymbol { HasConstantValue: true } constant) return Constant(constant);
            if (symbol is IFieldSymbol or IPropertySymbol && !Recorder.Visible(symbol))
            {
                var field = Hidden(symbol);
                bool write = !field.IsStatic && Writes(node);
                string name = writer.Placeholder(field, write);
                if (field.IsStatic) return ParseExpression($"{name}()").WithTriviaFrom(node);
                var receiver = (ExpressionSyntax)Visit(node.Expression)!;
                return InvocationExpression(IdentifierName(name), ArgumentList(SingletonSeparatedList(
                    Argument(receiver).WithRefKindKeyword(Token(write ? SyntaxKind.RefKeyword : SyntaxKind.InKeyword).WithTrailingTrivia(Space))))).WithTriviaFrom(node);
            }
            if (symbol is IMethodSymbol or IEventSymbol && !Recorder.Visible(symbol) && node.Parent is not InvocationExpressionSyntax)
                throw new NotRecorded($"it names {symbol.ContainingType?.Name}.{symbol.Name}, which other assemblies cannot reach");
            return node.WithExpression((ExpressionSyntax)Visit(node.Expression)!).WithName(Checked(node.Name));
        }

        public override SyntaxNode? VisitInvocationExpression(InvocationExpressionSyntax node)
        {
            if (Bound(node) is not IMethodSymbol called) return base.VisitInvocationExpression(node);
            var arguments = (ArgumentListSyntax)Visit(node.ArgumentList)!;
            if (called.ReducedFrom is { } extension) // x.Ext(a): the static form, which needs no using
            {
                var definition = extension.IsGenericMethod ? called.GetConstructedReducedFrom() ?? extension : extension;
                if (node.Expression is not MemberAccessExpressionSyntax access) throw new NotRecorded($"it calls extension {extension.Name} in a form the generator cannot copy");
                var receiver = (ExpressionSyntax)Visit(access.Expression)!;
                var first = Argument(receiver);
                if (extension.Parameters[0].RefKind == RefKind.Ref) first = first.WithRefKindKeyword(Token(SyntaxKind.RefKeyword).WithTrailingTrivia(Space));
                var target = Recorder.Visible(extension.OriginalDefinition) ? Qualified(definition) : IdentifierName(writer.Helper(extension.OriginalDefinition));
                return InvocationExpression(target, arguments.WithArguments(arguments.Arguments.Insert(0, first))).WithTriviaFrom(node);
            }

            if (!Recorder.Visible(called.OriginalDefinition) && called.MethodKind == MethodKind.Ordinary)
            {
                if (!called.IsStatic) throw new NotRecorded($"it calls {called.ContainingType.Name}.{called.Name}, which other assemblies cannot reach");
                return InvocationExpression(IdentifierName(writer.Helper(called.OriginalDefinition)), arguments).WithTriviaFrom(node);
            }

            return node.WithExpression((ExpressionSyntax)Visit(node.Expression)!).WithArgumentList(arguments);
        }

        public override SyntaxNode? VisitIdentifierName(IdentifierNameSyntax node)
        {
            if (node.IsVar && Bound(node) is ITypeSymbol) return node;
            if (!Leftmost(node)) return Checked(node);
            var symbol = Bound(node);
            switch (symbol)
            {
                case null when node.Identifier.ValueText == "nameof":
                    return node;
                case null:
                    throw new NotRecorded($"it names '{node.Identifier.ValueText}', which the generator could not bind");
                case ILocalSymbol or IParameterSymbol or IRangeVariableSymbol or ILabelSymbol or IDiscardSymbol:
                    return symbol is IParameterSymbol { IsThis: false } p && p.ContainingSymbol is IMethodSymbol owner
                        && !SymbolEqualityComparer.Default.Equals(owner, member) && owner.MethodKind != MethodKind.AnonymousFunction
                        ? throw new NotRecorded($"it names '{p.Name}' of another member")
                        : node;
                case INamespaceSymbol ns:
                    return ns.IsGlobalNamespace ? node : ParseName(ns.ToDisplayString(Symbols.Fqn)).WithTriviaFrom(node);
                case ITypeSymbol type:
                    return VisibleType(type) ? ParseTypeName(type.ToDisplayString(Symbols.Fqn)).WithTriviaFrom(node)
                        : throw new NotRecorded($"it names {type.Name}, which other assemblies cannot name");
                case IFieldSymbol { HasConstantValue: true } constant:
                    return Constant(constant).WithTriviaFrom(node);
                case IFieldSymbol or IPropertySymbol when !Recorder.Visible(symbol):
                {
                    var field = Hidden(symbol);
                    bool write = !field.IsStatic && Writes(node);
                    string name = writer.Placeholder(field, write);
                    return ParseExpression(field.IsStatic ? $"{name}()" : $"{name}({(write ? "ref" : "in")} @this)").WithTriviaFrom(node);
                }
                case IMethodSymbol { IsStatic: true } method when !Recorder.Visible(method):
                    if (node.Parent is InvocationExpressionSyntax) return node; // the call rewrites it
                    throw new NotRecorded($"it names {method.ContainingType.Name}.{method.Name}, which other assemblies cannot reach");
                case IFieldSymbol or IPropertySymbol or IMethodSymbol or IEventSymbol when symbol.IsStatic:
                    if (!Recorder.Visible(symbol)) throw new NotRecorded($"it names {symbol.ContainingType?.Name}.{symbol.Name}, which other assemblies cannot reach");
                    return ParseExpression($"{symbol.ContainingType!.ToDisplayString(Symbols.Fqn)}.{Code.Escape(symbol.Name)}").WithTriviaFrom(node);
                case IFieldSymbol or IPropertySymbol or IMethodSymbol or IEventSymbol: // a member of this: through @this
                    if (!Recorder.Visible(symbol)) throw new NotRecorded($"it calls {symbol.ContainingType?.Name}.{symbol.Name}, which other assemblies cannot reach");
                    return MemberAccessExpression(SyntaxKind.SimpleMemberAccessExpression, IdentifierName("@this"), node.WithoutTrivia()).WithTriviaFrom(node);
                default:
                    throw new NotRecorded($"it names '{node.Identifier.ValueText}', which the generator does not copy");
            }
        }

        public override SyntaxNode? VisitGenericName(GenericNameSyntax node)
        {
            var symbol = Bound(node);
            if (!Leftmost(node)) return symbol != null && !Recorder.Visible(symbol) && symbol is not ITypeSymbol
                ? throw new NotRecorded($"it names {symbol.Name}, which other assemblies cannot reach") : base.VisitGenericName(node);
            switch (symbol)
            {
                case ITypeSymbol type when VisibleType(type):
                    return ParseTypeName(type.ToDisplayString(Symbols.Fqn)).WithTriviaFrom(node);
                case IMethodSymbol { IsStatic: true } method when Recorder.Visible(method.OriginalDefinition):
                    return Qualified(method).WithTriviaFrom(node);
                default:
                    throw new NotRecorded($"it names {node.Identifier.ValueText}, which the generator does not copy");
            }
        }

        public override SyntaxNode? VisitAliasQualifiedName(AliasQualifiedNameSyntax node) =>
            node.Alias.Identifier.IsKind(SyntaxKind.GlobalKeyword) ? node : throw new NotRecorded("it names an extern alias");

        /// <summary>A name after a dot, in an initializer or a pattern: kept, when another assembly may name it.</summary>
        private SimpleNameSyntax Checked(SimpleNameSyntax name)
        {
            var symbol = Bound(name);
            if (symbol is IFieldSymbol or IPropertySymbol or IMethodSymbol or IEventSymbol && !Recorder.Visible(symbol.OriginalDefinition)
                && !(symbol is IMethodSymbol && name.Parent?.Parent is InvocationExpressionSyntax))
                throw new NotRecorded($"it names {symbol.ContainingType?.Name}.{symbol.Name}, which other assemblies cannot reach");
            if (symbol is ITypeSymbol type && !VisibleType(type)) throw new NotRecorded($"it names {type.Name}, which other assemblies cannot name");
            return name is GenericNameSyntax generic ? generic.WithTypeArgumentList((TypeArgumentListSyntax)Visit(generic.TypeArgumentList)!) : name;
        }

        /// <summary>The field a hidden field or auto-property is (its backing field), or the reason it is not recorded.</summary>
        private static IFieldSymbol Hidden(ISymbol symbol) => symbol switch
        {
            IFieldSymbol field => field,
            IPropertySymbol property when Symbols.BackingField(property) is { } backing => backing,
            _ => throw new NotRecorded($"it reads property {symbol.ContainingType?.Name}.{symbol.Name}, which other assemblies cannot reach"),
        };

        private bool Writes(SyntaxNode node) => model.GetOperation(node, Ct) is not { } op || Uses.MayWrite(op);

        private static ExpressionSyntax Constant(IFieldSymbol constant) =>
            LambdaPass.Constant(constant.ConstantValue, constant.Type) is { } value ? ParseExpression(value)
                : throw new NotRecorded($"it names constant {constant.Name}, whose value the generator cannot write");

        private static ExpressionSyntax Qualified(IMethodSymbol method)
        {
            string name = method.IsGenericMethod ? $"{Code.Escape(method.Name)}<{string.Join(",", method.TypeArguments.Select(t => t.ToDisplayString(Symbols.Fqn)))}>" : Code.Escape(method.Name);
            return ParseExpression($"{method.ContainingType.ToDisplayString(Symbols.Fqn)}.{name}");
        }

        /// <summary>A name that starts an expression or a type: not a member after a dot, a named argument or an initialized member.</summary>
        private static bool Leftmost(SimpleNameSyntax node) => node.Parent switch
        {
            MemberAccessExpressionSyntax access => access.Expression == node,
            QualifiedNameSyntax qualified => qualified.Left == node,
            MemberBindingExpressionSyntax or NameColonSyntax or NameEqualsSyntax or AliasQualifiedNameSyntax or ExplicitInterfaceSpecifierSyntax => false,
            AssignmentExpressionSyntax { Parent: InitializerExpressionSyntax } assignment => assignment.Left != node,
            _ => true,
        };
    }

    /// <summary>A node's tokens on one line: a space only where two words or two operators would run together.</summary>
    private static string Compact(SyntaxNode node)
    {
        var sb = new StringBuilder();
        char last = ' ';
        foreach (var token in node.DescendantTokens())
        {
            string text = token.Text;
            if (text.Length == 0) continue;
            char first = text[0];
            if (sb.Length > 0 && (Word(last) && Word(first) || !Word(last) && !Word(first) && !char.IsWhiteSpace(last) && first != '(' && first != ')' && first != ';' && first != ','
                    && last != '(' && last != ')' && last != '{' && last != '}' && last != ';' && last != ','))
                sb.Append(' ');
            sb.Append(text);
            last = text[text.Length - 1];
        }
        return sb.ToString();

        static bool Word(char c) => char.IsLetterOrDigit(c) || c == '_' || c == '@' || c == '"' || c == '\'';
    }
