using System;
using System.Linq;
using Microsoft.CodeAnalysis.CSharp;

namespace EasyEcs.Generator;

/// <summary>Tiny helpers for arity templates: Code.List(3, i => $"T{i}") == "T1, T2, T3".</summary>
internal static class Code
{
    public static string List(int n, Func<int, string> item, string separator = ", ") =>
        string.Join(separator, Enumerable.Range(1, n).Select(item));

    public static string Lines(int n, Func<int, string> item) => List(n, item, "\n");

    public static string TypeParams(int n) => List(n, i => $"T{i}");

    public static string Constraints(int n, string indent) =>
        Lines(n, i => $"{indent}where T{i} : struct, IComponent");

    public const string Header = "// <auto-generated/>\n#nullable disable\n";

    /// <summary>
    /// The <c>[GeneratedCode]</c> attribute of a generated class or member, naming <paramref name="tool"/> (the analyzer
    /// tells the generator's members apart by <see cref="Symbols.GeneratorName"/>, Symbols.IsGenerated).
    /// </summary>
    public static string GeneratedCode(string tool) =>
        $"[global::System.CodeDom.Compiler.GeneratedCode(\"{tool}\", \"{ComponentGenerator.Version}\")]";

    /// <summary>The attribute of a generated module initializer (registrations run as the assembly loads).</summary>
    public const string ModuleInitializer = "[global::System.Runtime.CompilerServices.ModuleInitializer]";

    /// <summary>A name as generated code writes it: a keyword gets its <c>@</c> (<c>@class</c>).</summary>
    public static string Escape(string name) => SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

    /// <summary>The FNV-1a hash of <paramref name="text"/>'s characters: stable across processes, unlike <c>GetHashCode</c>.</summary>
    public static uint Fnv(string text)
    {
        uint hash = 2166136261;
        foreach (char c in text) hash = (hash ^ c) * 16777619;
        return hash;
    }
}
