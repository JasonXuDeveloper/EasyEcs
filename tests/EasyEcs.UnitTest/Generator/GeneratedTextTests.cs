/// <summary>
/// The generated text against the rules of audit-generator, "The generated text": the generators run over the battle
/// server, GeneratorBenchmark's modules and the corpora of every vector form (KernelTests, StructuralLoopTests,
/// FusionTests, LambdaPassTests), and each kind of line that does nothing is counted. A count may only fall: a change
/// that adds such lines fails here, and a cleanup lowers the count it removes (the budgets below, docs/plans/backlog.md
/// G14-G17). Output bytes are GeneratorBenchmark's column.
/// </summary>
public class GeneratedTextTests
{
    /// <summary>The most of each kind the output may hold (the counts at the last cleanup).</summary>
    private static readonly Dictionary<string, int> Budget = new()
    {
        ["global:: outside using directives"] = 17_810, // type names said once in a file, and those in doc comments
        ["parentheses around a literal, a name or parentheses"] = 0,
        ["identity copies"] = 40, // a lane held under a name of its own where the generator cannot see that neither is written again
        ["locals never read"] = 4_562,
        ["a mark zeroed then OR-ed once"] = 0,
        ["parentheses precedence does not need"] = 0,
        ["temporaries copied into a name"] = 0,
        ["a lane declared default, then written"] = 0,
        ["setup locals read once"] = 0,
        ["all lanes and-ed with a mask"] = 6, // a bail's test keeps AllBitsSet: written without it, the test moved in KernelBenchmark's Share, ~10 % slower
        ["a pass mask spelled again"] = 0,
        ["a lane written twice under complementary masks"] = 0,
        ["the first loop's rows counted from i = 0"] = 0,
        ["a width's hardware test repeated in the schedule line"] = 0,
        ["this. where the name alone binds"] = 0,
        ["a job field set to its default"] = 0,
        ["empty methods"] = 1,
        ["constants created in a method"] = 6_014,
    };

    /// <summary>The corpus's generated bytes at the last cleanup: a change that writes more text raises it on purpose.</summary>
    private const int Bytes = 11_524_667;

    [Test]
    public void TheGeneratedTextHoldsNoMoreDeadLinesThanItsBudget()
    {
        var (trees, compilation) = Generate();
        var counts = Count(trees, compilation);
        foreach (var (kind, count) in counts)
            TestContext.Out.WriteLine($"{kind}: {count}{(count > 0 && Examples.TryGetValue(kind, out var example) ? $" (first: {example})" : "")}");
        int bytes = trees.Sum(t => t.Length);
        TestContext.Out.WriteLine($"generated bytes: {bytes} in {trees.Length} files");
        Assert.Multiple(() =>
        {
            foreach (var (kind, count) in counts)
                Assert.That(count, Is.LessThanOrEqualTo(Budget[kind]), $"{kind}: {count}, budget {Budget[kind]}");
            Assert.That(bytes, Is.LessThanOrEqualTo(Bytes), $"generated bytes: {bytes}, budget {Bytes}");
        });
    }

    /// <summary>The generated trees of the corpus (SystemGenerator's and the other generators' files) and the compilation holding them.</summary>
    private static (SyntaxTree[] Trees, Compilation Compilation) Generate()
    {
        var sources = GeneratorCorpus.Sources(false).Select((s, i) => (Path: $"Corpus{i}.cs", Text: s)).ToList();
        foreach (var file in new[] { "Fixtures.cs", "VectorLoops/KernelTests.cs", "VectorLoops/StructuralLoopTests.cs", "Systems/FusionTests.cs", "Systems/LambdaPassTests.cs" })
            sources.Add((file, File.ReadAllText(Path.Combine(Here(), "..", file))));
        var trees = sources.Select(s => CSharpSyntaxTree.ParseText(s.Text, GeneratorCorpus.Parse, path: s.Path)).ToArray();
        var references = GeneratorCorpus.References().Add(MetadataReference.CreateFromFile(typeof(TestAttribute).Assembly.Location));
        var compilation = GeneratorCorpus.Compilation([.. trees], references);
        var driver = GeneratorCorpus.Driver().RunGeneratorsAndUpdateCompilation(compilation, out var generated, out _);
        return (driver.GetRunResult().GeneratedTrees.ToArray(), generated);
    }

    private static string Here([CallerFilePath] string path = "") => Path.GetDirectoryName(path)!;

    /// <summary>The first line of each kind the last count found, for the test's output.</summary>
    private static readonly Dictionary<string, string> Examples = [];

    private static void Note(string kind, SyntaxNode node)
    {
        if (Examples.ContainsKey(kind)) return;
        var line = node.GetLocation().GetLineSpan();
        Examples[kind] = $"{Path.GetFileName(line.Path)}:{line.StartLinePosition.Line + 1}: {node.SyntaxTree.GetText().Lines[line.StartLinePosition.Line].ToString().Trim()}";
    }

    private static List<(string Kind, int Count)> Count(SyntaxTree[] trees, Compilation compilation)
    {
        Examples.Clear();
        int qualified = 0, parentheses = 0, copies = 0, unread = 0, marks = 0, empty = 0, constants = 0;
        int needless = 0, declaredDefault = 0, temporaries = 0, heldOnce = 0, allLanes = 0, passMasks = 0, complementary = 0, fromZero = 0, repeatedTerms = 0, thisQualified = 0, defaults = 0;
        foreach (var tree in trees)
        {
            var root = tree.GetRoot();
            var model = compilation.GetSemanticModel(tree);
            string whole = tree.GetText().ToString();
            foreach (var p in root.DescendantNodes().OfType<ParenthesizedExpressionSyntax>().Where(Needless))
            {
                needless++;
                Note("parentheses precedence does not need", p);
            }
            allLanes += root.DescendantNodes().OfType<BinaryExpressionSyntax>().Count(b => b.IsKind(SyntaxKind.BitwiseAndExpression)
                && (AllBits(b.Left) || AllBits(b.Right)));
            // the first vector loop of a run tests rows - i where i was just set to 0
            fromZero += Regex.Matches(whole, @"nint i = 0[^;\n]*;\n\s*if \([^\n]*\b(?:rows|lanes) - i >=").Count;
            foreach (var field in root.DescendantNodes().OfType<VariableDeclaratorSyntax>().Where(v => v.Identifier.Text == "__loops"))
                foreach (var or in field.DescendantNodes().OfType<BinaryExpressionSyntax>().Where(b => b.IsKind(SyntaxKind.LogicalOrExpression) && b.Parent is not BinaryExpressionSyntax { RawKind: (int)SyntaxKind.LogicalOrExpression }))
                {
                    var widths = Operands(or, SyntaxKind.LogicalOrExpression).Select(w => Operands(w, SyntaxKind.LogicalAndExpression).Select(t => t.ToString()).ToHashSet()).ToList();
                    repeatedTerms += widths.Count(w => widths.Any(o => !ReferenceEquals(o, w) && o.IsSubsetOf(w)));
                }
            foreach (var access in root.DescendantNodes().OfType<MemberAccessExpressionSyntax>().Where(m => m.Expression is ThisExpressionSyntax))
                if (model.GetSymbolInfo(access).Symbol is { } member
                    && model.LookupSymbols(access.SpanStart, name: access.Name.Identifier.Text) is [var alone] && SymbolEqualityComparer.Default.Equals(alone, member))
                {
                    thisQualified++;
                    Note("this. where the name alone binds", access);
                }
            foreach (var assignment in root.DescendantNodes().OfType<AssignmentExpressionSyntax>().Where(a => a.IsKind(SyntaxKind.SimpleAssignmentExpression)))
                if (model.GetSymbolInfo(assignment.Left).Symbol is IFieldSymbol { ContainingType.IsRefLikeType: true } && IsDefault(assignment.Right, model))
                {
                    defaults++;
                    Note("a job field set to its default", assignment);
                }
            // a vector of rows' statements (a block's own, not those of the blocks it holds) spelling one pass mask twice
            foreach (var body in root.DescendantNodes().OfType<BlockSyntax>())
                foreach (var again in body.Statements.Where(st => st is not (BlockSyntax or IfStatementSyntax or ForStatementSyntax or WhileStatementSyntax))
                    .SelectMany(st => st.DescendantNodes().OfType<InvocationExpressionSyntax>())
                    .Where(c => c.Expression is MemberAccessExpressionSyntax { Name: GenericNameSyntax { Identifier.Text: "As" } } && c.ArgumentList.Arguments is [{ Expression: IdentifierNameSyntax { Identifier.Text: "__pass" } }])
                    .GroupBy(c => c.ToString()).Where(g => g.Count() > 1))
                {
                    passMasks += again.Count() - 1;
                    Note("a pass mask spelled again", again.Last());
                }
            foreach (var line in tree.GetText().Lines)
            {
                string text = line.ToString();
                if (!text.TrimStart().StartsWith("using ", System.StringComparison.Ordinal))
                    qualified += (text.Length - text.Replace("global::", "").Length) / "global::".Length;
            }
            parentheses += root.DescendantNodes().OfType<ParenthesizedExpressionSyntax>()
                .Count(p => p.Expression is LiteralExpressionSyntax or IdentifierNameSyntax or ParenthesizedExpressionSyntax);
            empty += root.DescendantNodes().OfType<MethodDeclarationSyntax>().Count(m => m.Body is { Statements.Count: 0 });
            constants += root.DescendantNodes().OfType<InvocationExpressionSyntax>().Count(call =>
                call.Expression is MemberAccessExpressionSyntax { Name.Identifier.Text: "Create" } && call.ArgumentList.Arguments.Count == 1
                && Unwrapped(call.ArgumentList.Arguments[0].Expression) is LiteralExpressionSyntax
                && call.FirstAncestorOrSelf<BaseMethodDeclarationSyntax>() != null);
            // x = Select(m, a, x); x = Select(~m, b, x); (an if / else, a switch's sections): x = Select(m, a, b), whose
            // masked word selects by __pass once
            foreach (var block in root.DescendantNodes().OfType<BlockSyntax>())
                for (int k = 0; k + 1 < block.Statements.Count; k++)
                    if (LaneSelect(block.Statements[k]) is { } first && LaneSelect(block.Statements[k + 1]) is { } second
                        && first.Target == second.Target && Complements(first.Mask, second.Mask))
                    {
                        complementary++;
                        Note("a lane written twice under complementary masks", block.Statements[k + 1]);
                    }
            foreach (var block in root.DescendantNodes().OfType<BlockSyntax>())
            {
                var statements = block.Statements;
                for (int k = 0; k < statements.Count; k++)
                {
                    if (statements[k] is not LocalDeclarationStatementSyntax { Declaration.Variables: [{ Initializer.Value: var value } variable] }) continue;
                    string name = variable.Identifier.Text;
                    var rest = statements.Skip(k + 1).SelectMany(s => s.DescendantNodesAndSelf()).ToArray();
                    // var a = b; with neither written again: a second name for one value
                    if (value is IdentifierNameSyntax source && !rest.Any(n => Writes(n, name) || Writes(n, source.Identifier.Text)))
                    {
                        copies++;
                        Note("identity copies", variable);
                    }
                    var reads = rest.OfType<IdentifierNameSyntax>().Where(n => n.Identifier.Text == name).ToArray();
                    // var t = a + b; x = t; with t read nowhere else: x = a + b
                    if (name.StartsWith("__t", System.StringComparison.Ordinal) && value is not IdentifierNameSyntax && reads.Length == 1
                        && reads[0].Parent is AssignmentExpressionSyntax { RawKind: (int)SyntaxKind.SimpleAssignmentExpression, Left: IdentifierNameSyntax } copy && copy.Right == reads[0])
                    {
                        temporaries++;
                        Note("temporaries copied into a name", variable);
                    }
                    // ref readonly T __p3 = ref s3; read once: read s3 there
                    if (name.StartsWith("__p", System.StringComparison.Ordinal) && reads.Length == 1
                        && Unwrapped(value is RefExpressionSyntax r ? r.Expression : value) is IdentifierNameSyntax or MemberAccessExpressionSyntax)
                    {
                        heldOnce++;
                        Note("setup locals read once", variable);
                    }
                    // var c = default(V); c = a + b; (its first use writes it, in this block): var c = a + b
                    if (value is DefaultExpressionSyntax && reads.FirstOrDefault() is { Parent: AssignmentExpressionSyntax { RawKind: (int)SyntaxKind.SimpleAssignmentExpression, Parent: ExpressionStatementSyntax { Parent: var holder } } first } written
                        && first.Left == written && holder == block && !first.Right.DescendantNodesAndSelf().OfType<IdentifierNameSyntax>().Any(n => n.Identifier.Text == name))
                    {
                        declaredDefault++;
                        Note("a lane declared default, then written", variable);
                    }
                    // var d = ...Zero; d |= x; and nothing else written to it
                    if (value is MemberAccessExpressionSyntax { Name.Identifier.Text: "Zero" }
                        && rest.Count(n => Writes(n, name)) == 1 && rest.Any(n => n is AssignmentExpressionSyntax { RawKind: (int)SyntaxKind.OrAssignmentExpression, Left: IdentifierNameSyntax target } && target.Identifier.Text == name))
                        marks++;
                }
            }
            foreach (var body in root.DescendantNodes().OfType<BaseMethodDeclarationSyntax>().Select(m => m.Body).OfType<BlockSyntax>())
            {
                if (body.Statements.Count == 0) continue;
                var flow = model.AnalyzeDataFlow(body.Statements.First(), body.Statements.Last());
                if (flow is not { Succeeded: true }) continue;
                unread += flow.VariablesDeclared.Count(v => v is ILocalSymbol && !flow.ReadInside.Contains(v));
            }
        }
        return
        [
            ("global:: outside using directives", qualified),
            ("parentheses around a literal, a name or parentheses", parentheses),
            ("parentheses precedence does not need", needless),
            ("identity copies", copies),
            ("temporaries copied into a name", temporaries),
            ("a lane declared default, then written", declaredDefault),
            ("locals never read", unread),
            ("setup locals read once", heldOnce),
            ("a mark zeroed then OR-ed once", marks),
            ("all lanes and-ed with a mask", allLanes),
            ("a pass mask spelled again", passMasks),
            ("a lane written twice under complementary masks", complementary),
            ("the first loop's rows counted from i = 0", fromZero),
            ("a width's hardware test repeated in the schedule line", repeatedTerms),
            ("this. where the name alone binds", thisQualified),
            ("a job field set to its default", defaults),
            ("empty methods", empty),
            ("constants created in a method", constants),
        ];

        // x = V.ConditionalSelect(mask, value, x): the target and the mask's text (an As<...>(mask) unwrapped)
        static (string Target, string Mask)? LaneSelect(StatementSyntax statement)
        {
            if (statement is not ExpressionStatementSyntax { Expression: AssignmentExpressionSyntax { RawKind: (int)SyntaxKind.SimpleAssignmentExpression, Left: IdentifierNameSyntax target } assignment }
                || Unwrapped(assignment.Right) is not InvocationExpressionSyntax { Expression: MemberAccessExpressionSyntax { Name.Identifier.Text: "ConditionalSelect" } } select
                || select.ArgumentList.Arguments is not [var mask, _, { Expression: IdentifierNameSyntax kept }] || kept.Identifier.Text != target.Identifier.Text)
                return null;
            var m = Unwrapped(mask.Expression);
            if (m is InvocationExpressionSyntax { Expression: MemberAccessExpressionSyntax { Name: GenericNameSyntax { Identifier.Text: "As" } } } cast && cast.ArgumentList.Arguments.Count == 1)
                m = Unwrapped(cast.ArgumentList.Arguments[0].Expression);
            return (target.Identifier.Text, m.ToString());
        }

        // m and ~m, or m & p and ~m & p
        static bool Complements(string a, string b)
        {
            if (b == "~" + a || a == "~" + b) return true;
            int x = a.LastIndexOf(" & ", System.StringComparison.Ordinal), y = b.LastIndexOf(" & ", System.StringComparison.Ordinal);
            return x > 0 && y > 0 && a.Substring(x) == b.Substring(y) && Complements(a.Substring(0, x), b.Substring(0, y));
        }

        // V.AllBitsSet: the lanes of a whole vector
        static bool AllBits(ExpressionSyntax e) => Unwrapped(e) is MemberAccessExpressionSyntax { Name.Identifier.Text: "AllBitsSet" };

        // the operands of a chain of one operator: a || b || c
        static IEnumerable<ExpressionSyntax> Operands(ExpressionSyntax e, SyntaxKind kind) =>
            Unwrapped(e) is BinaryExpressionSyntax b && b.IsKind(kind) ? Operands(b.Left, kind).Concat(Operands(b.Right, kind)) : [Unwrapped(e)];

        // default, default(T), or new T() of a struct whose constructor the compiler wrote
        static bool IsDefault(ExpressionSyntax e, SemanticModel model) => Unwrapped(e) switch
        {
            LiteralExpressionSyntax l => l.IsKind(SyntaxKind.DefaultLiteralExpression),
            DefaultExpressionSyntax => true,
            BaseObjectCreationExpressionSyntax { ArgumentList.Arguments.Count: 0, Initializer: null } c
                => model.GetSymbolInfo(c).Symbol is IMethodSymbol { IsImplicitlyDeclared: true, ContainingType.IsValueType: true },
            _ => false,
        };

        // parentheses whose removal leaves the expression they sit in parsed the same
        static bool Needless(ParenthesizedExpressionSyntax p)
        {
            SyntaxNode top = p;
            while (top.Parent is ExpressionSyntax or ArgumentSyntax or ArgumentListSyntax or BracketedArgumentListSyntax) top = top.Parent;
            if (top is not ExpressionSyntax) return false;
            string text = top.ToString();
            int open = p.SpanStart - top.SpanStart, close = p.Span.End - 1 - top.SpanStart;
            var reparsed = SyntaxFactory.ParseExpression(text.Remove(close, 1).Remove(open, 1));
            return !reparsed.ContainsDiagnostics && reparsed.FullSpan.Length == text.Length - 2 && Shape(reparsed) == Shape(top) && !ForClarity(p);
        }

        // parentheses a reader keeps between two operators of different kinds (Tidy.Clear): (x >> k) & 1, x >> (64 - n),
        // and around a negative operand or cast (a - (-1), (int)(-1))
        static bool ForClarity(ParenthesizedExpressionSyntax p)
        {
            var inner = p.Expression;
            bool negative = inner is PrefixUnaryExpressionSyntax { RawKind: (int)SyntaxKind.UnaryMinusExpression or (int)SyntaxKind.UnaryPlusExpression };
            if (p.Parent is CastExpressionSyntax) return negative; // (int)(-1)
            if (p.Parent is not BinaryExpressionSyntax outer) return false;
            if (negative) return true;
            if (inner is not BinaryExpressionSyntax b) return false;
            int i = Level(b.OperatorToken.Text), o = Level(outer.OperatorToken.Text);
            return i is 12 or 13 ? o is not (12 or 13 or 10 or 9) : i is 10 or 9 ? o is not (5 or 4) : b.OperatorToken.Text != outer.OperatorToken.Text;
        }

        static int Level(string op) => op switch
        {
            "*" or "/" or "%" => 13, "+" or "-" => 12, "<<" or ">>" or ">>>" => 11, "<" or ">" or "<=" or ">=" => 10,
            "==" or "!=" => 9, "&" => 8, "^" => 7, "|" => 6, "&&" => 5, "||" => 4, "??" => 3, _ => 0,
        };

        // the kinds of a tree, parentheses skipped
        static string Shape(SyntaxNode node)
        {
            var sb = new System.Text.StringBuilder();
            void Walk(SyntaxNode n)
            {
                if (n is ParenthesizedExpressionSyntax inner)
                {
                    Walk(inner.Expression);
                    return;
                }
                sb.Append((int)n.RawKind).Append('(');
                foreach (var child in n.ChildNodes()) Walk(child);
                sb.Append(')');
            }
            Walk(node);
            return sb.ToString();
        }

        static ExpressionSyntax Unwrapped(ExpressionSyntax e)
        {
            while (e is ParenthesizedExpressionSyntax p) e = p.Expression;
            while (e is CastExpressionSyntax c) e = Unwrapped(c.Expression);
            return e;
        }

        static bool Writes(SyntaxNode node, string name) => node switch
        {
            AssignmentExpressionSyntax { Left: IdentifierNameSyntax left } => left.Identifier.Text == name,
            ArgumentSyntax { RefKindKeyword.RawKind: not 0, Expression: IdentifierNameSyntax arg } => arg.Identifier.Text == name,
            PrefixUnaryExpressionSyntax { Operand: IdentifierNameSyntax operand, RawKind: (int)SyntaxKind.PreIncrementExpression or (int)SyntaxKind.PreDecrementExpression } => operand.Identifier.Text == name,
            PostfixUnaryExpressionSyntax { Operand: IdentifierNameSyntax operand } => operand.Identifier.Text == name,
            RefExpressionSyntax { Expression: IdentifierNameSyntax r } => r.Identifier.Text == name,
            _ => false,
        };
    }
}
