using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Runtime.CompilerServices;
using EasyEcs.Benchmark;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using NUnit.Framework;

namespace EasyEcs.UnitTest;

/// <summary>
/// The generated text against the rules of audit-generator, "The generated text": the generators run over the battle
/// server, GeneratorBenchmark's modules and the corpora of every vector form (KernelTests, StructuralLoopTests,
/// FusionTests, LambdaPassTests), and each kind of line that does nothing is counted. A count may only fall: a change
/// that adds such lines fails here, and a cleanup lowers the count it removes (the budgets below, docs/plans/backlog.md
/// G14-G17). Output bytes are GeneratorBenchmark's column.
/// </summary>
public class GeneratedTextTests
{
    /// <summary>The most of each kind the output may hold (the counts at the last cleanup).</summary>
    private static readonly Dictionary<string, int> Budget = new()
    {
        ["global:: outside using directives"] = 100_790,
        ["parentheses around a literal, a name or parentheses"] = 333,
        ["identity copies"] = 108,
        ["locals never read"] = 4_572,
        ["a mark zeroed then OR-ed once"] = 1_308,
        ["empty methods"] = 1,
        ["constants created in a method"] = 5_982,
    };

    [Test]
    public void TheGeneratedTextHoldsNoMoreDeadLinesThanItsBudget()
    {
        var (trees, compilation) = Generate();
        var counts = Count(trees, compilation);
        foreach (var (kind, count) in counts) TestContext.Out.WriteLine($"{kind}: {count}");
        TestContext.Out.WriteLine($"generated bytes: {trees.Sum(t => t.Length)} in {trees.Length} files");
        Assert.Multiple(() =>
        {
            foreach (var (kind, count) in counts)
                Assert.That(count, Is.LessThanOrEqualTo(Budget[kind]), $"{kind}: {count}, budget {Budget[kind]}");
        });
    }

    /// <summary>The generated trees of the corpus (SystemGenerator's and the other generators' files) and the compilation holding them.</summary>
    private static (SyntaxTree[] Trees, Compilation Compilation) Generate()
    {
        var sources = GeneratorCorpus.Sources(false).Select((s, i) => (Path: $"Corpus{i}.cs", Text: s)).ToList();
        foreach (var file in new[] { "Fixtures.cs", "KernelTests.cs", "StructuralLoopTests.cs", "FusionTests.cs", "LambdaPassTests.cs" })
            sources.Add((file, File.ReadAllText(Path.Combine(Here(), file))));
        var trees = sources.Select(s => CSharpSyntaxTree.ParseText(s.Text, GeneratorCorpus.Parse, path: s.Path)).ToArray();
        var references = GeneratorCorpus.References().Add(MetadataReference.CreateFromFile(typeof(TestAttribute).Assembly.Location));
        var compilation = GeneratorCorpus.Compilation([.. trees], references);
        var driver = GeneratorCorpus.Driver().RunGeneratorsAndUpdateCompilation(compilation, out var generated, out _);
        return (driver.GetRunResult().GeneratedTrees.ToArray(), generated);
    }

    private static string Here([CallerFilePath] string path = "") => Path.GetDirectoryName(path)!;

    private static List<(string Kind, int Count)> Count(SyntaxTree[] trees, Compilation compilation)
    {
        int qualified = 0, parentheses = 0, copies = 0, unread = 0, marks = 0, empty = 0, constants = 0;
        foreach (var tree in trees)
        {
            var root = tree.GetRoot();
            var model = compilation.GetSemanticModel(tree);
            foreach (var line in tree.GetText().Lines)
            {
                string text = line.ToString();
                if (!text.TrimStart().StartsWith("using ", System.StringComparison.Ordinal))
                    qualified += (text.Length - text.Replace("global::", "").Length) / "global::".Length;
            }
            parentheses += root.DescendantNodes().OfType<ParenthesizedExpressionSyntax>()
                .Count(p => p.Expression is LiteralExpressionSyntax or IdentifierNameSyntax or ParenthesizedExpressionSyntax);
            empty += root.DescendantNodes().OfType<MethodDeclarationSyntax>().Count(m => m.Body is { Statements.Count: 0 });
            constants += root.DescendantNodes().OfType<InvocationExpressionSyntax>().Count(call =>
                call.Expression is MemberAccessExpressionSyntax { Name.Identifier.Text: "Create" } && call.ArgumentList.Arguments.Count == 1
                && Unwrapped(call.ArgumentList.Arguments[0].Expression) is LiteralExpressionSyntax
                && call.FirstAncestorOrSelf<BaseMethodDeclarationSyntax>() != null);
            foreach (var block in root.DescendantNodes().OfType<BlockSyntax>())
            {
                var statements = block.Statements;
                for (int k = 0; k < statements.Count; k++)
                {
                    if (statements[k] is not LocalDeclarationStatementSyntax { Declaration.Variables: [{ Initializer.Value: var value } variable] }) continue;
                    string name = variable.Identifier.Text;
                    var rest = statements.Skip(k + 1).SelectMany(s => s.DescendantNodesAndSelf()).ToArray();
                    // var a = b; with neither written again: a second name for one value
                    if (value is IdentifierNameSyntax source && !rest.Any(n => Writes(n, name) || Writes(n, source.Identifier.Text))) copies++;
                    // var d = ...Zero; d |= x; and nothing else written to it
                    if (value is MemberAccessExpressionSyntax { Name.Identifier.Text: "Zero" }
                        && rest.Count(n => Writes(n, name)) == 1 && rest.Any(n => n is AssignmentExpressionSyntax { RawKind: (int)SyntaxKind.OrAssignmentExpression, Left: IdentifierNameSyntax target } && target.Identifier.Text == name))
                        marks++;
                }
            }
            foreach (var body in root.DescendantNodes().OfType<BaseMethodDeclarationSyntax>().Select(m => m.Body).OfType<BlockSyntax>())
            {
                if (body.Statements.Count == 0) continue;
                var flow = model.AnalyzeDataFlow(body.Statements.First(), body.Statements.Last());
                if (flow is not { Succeeded: true }) continue;
                unread += flow.VariablesDeclared.Count(v => v is ILocalSymbol && !flow.ReadInside.Contains(v));
            }
        }
        return
        [
            ("global:: outside using directives", qualified),
            ("parentheses around a literal, a name or parentheses", parentheses),
            ("identity copies", copies),
            ("locals never read", unread),
            ("a mark zeroed then OR-ed once", marks),
            ("empty methods", empty),
            ("constants created in a method", constants),
        ];

        static ExpressionSyntax Unwrapped(ExpressionSyntax e)
        {
            while (e is ParenthesizedExpressionSyntax p) e = p.Expression;
            while (e is CastExpressionSyntax c) e = Unwrapped(c.Expression);
            return e;
        }

        static bool Writes(SyntaxNode node, string name) => node switch
        {
            AssignmentExpressionSyntax { Left: IdentifierNameSyntax left } => left.Identifier.Text == name,
            ArgumentSyntax { RefKindKeyword.RawKind: not 0, Expression: IdentifierNameSyntax arg } => arg.Identifier.Text == name,
            PrefixUnaryExpressionSyntax { Operand: IdentifierNameSyntax operand, RawKind: (int)SyntaxKind.PreIncrementExpression or (int)SyntaxKind.PreDecrementExpression } => operand.Identifier.Text == name,
            PostfixUnaryExpressionSyntax { Operand: IdentifierNameSyntax operand } => operand.Identifier.Text == name,
            RefExpressionSyntax { Expression: IdentifierNameSyntax r } => r.Identifier.Text == name,
            _ => false,
        };
    }
}
