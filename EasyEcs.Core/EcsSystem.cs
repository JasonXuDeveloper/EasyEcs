using System;
using System.ComponentModel;

namespace EasyEcs;

/// <summary>
/// Logic that runs on a world. Lifecycle: <see cref="OnCreate"/> when added, then every update <see cref="OnUpdate"/>
/// followed by the <see cref="ForEachAttribute">[ForEach]</see> methods, and <see cref="OnDestroy"/> when removed or
/// when the world is disposed. Everything runs synchronously within <see cref="World.Update()"/> (or
/// <see cref="World.Update{TGroup}"/> for systems in a <see cref="UpdateInGroupAttribute{TGroup}">group</see>): on the
/// calling thread, or with <see cref="WorldOptions.Parallel"/> on a thread-pool thread next to systems whose
/// <see cref="SystemAccess">access</see> does not conflict.
/// </summary>
public abstract class EcsSystem
{
    /// <summary>The world this system belongs to (set before <see cref="OnCreate"/>).</summary>
    public World World { get; internal set; }

    /// <summary>
    /// Execution order: lower runs first; equal priorities run in registration order (or, with
    /// <see cref="WorldOptions.Parallel"/>, at the same time when their <see cref="SystemAccess">access</see> allows it).
    /// </summary>
    public virtual int Priority => 0;

    /// <summary>Run every N-th world update (1 = every update).</summary>
    public virtual int UpdateInterval => 1;

    /// <summary>Index of the system's group in its world (0 = default group).</summary>
    internal int Group;

    /// <summary>Disabled systems are skipped by <see cref="World.Update()"/>.</summary>
    public bool Enabled { get; set; } = true;

    /// <summary>
    /// The world's <see cref="World.ChangeTick"/> when this system last ran (0 before its first run): its
    /// <c>[Changed&lt;T&gt;]</c> methods select rows written after that tick, so not their own writes of that run.
    /// </summary>
    public ulong LastRunTick { get; internal set; }

    /// <summary>Run count and time of this system; recorded only with <see cref="WorldOptions.MeasureSystems"/>.</summary>
    public SystemStats Stats { get; internal set; }

    /// <summary>Called once when the system is added to a world.</summary>
    protected virtual void OnCreate()
    {
    }

    /// <summary>Called every update before the system's [ForEach] methods.</summary>
    protected virtual void OnUpdate()
    {
    }

    /// <summary>Called once when the system is removed or the world is disposed.</summary>
    protected virtual void OnDestroy()
    {
    }

    /// <summary>Generated by EasyEcs.Generator: runs the [ForEach] methods. Do not override by hand.</summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    protected virtual void GeneratedUpdate()
    {
    }

    /// <summary>
    /// Generated by EasyEcs.Generator from the [ForEach] parameters. Do not override by hand. Without generated code a
    /// system runs alone.
    /// </summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    protected virtual void GeneratedAccess(ref SystemAccess access) => access.RunsAlone();

    /// <summary>
    /// Generated by EasyEcs.Generator: the most derived system type it generated code for. Do not override by hand. A
    /// system whose runtime type is further derived runs alone: the generator never saw that type's OnUpdate.
    /// </summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    protected virtual Type GeneratedFor => typeof(EcsSystem);

    /// <summary>What the system reads and writes, declared once by <see cref="World.AddSystem(EcsSystem)"/>.</summary>
    internal SystemAccess Access;

    // Entry points used by World (hooks stay protected so user overrides are plain `protected override`).
    internal void Create() => OnCreate();

    internal void DeclareAccess()
    {
        Access = default;
        GeneratedAccess(ref Access);
        if (GetType() != GeneratedFor) Access.RunsAlone(); // a subclass without generated code may override OnUpdate
    }

    internal void Update()
    {
        OnUpdate();
        GeneratedUpdate();
    }

    internal void Destroy() => OnDestroy();
}
