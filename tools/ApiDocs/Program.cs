using System.Text;
using System.Xml.Linq;
using ApiDocs;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

// dotnet run --project tools/ApiDocs [-- [--zh-scaffold] [output-dir]]
// Writes one MDX page per public type of EasyEcs.Core (a T1..T9 family is one page) into docs/content/reference/,
// with an index and meta.json, from the built assembly and its XML documentation, in English (<page>.mdx) and in
// Chinese (<page>.zh.mdx, from the translations in tools/ApiDocs/zh/). Complexity comes from the API tables
// (docs/content/api.mdx, api.zh.mdx). Deterministic: CI regenerates the pages and fails if they differ from the
// commit; the tool exits with 1 when a translation is missing, stale or orphaned.
var root = Root();
bool scaffold = args.Contains("--zh-scaffold");
var paths = args.Where(a => !a.StartsWith("--", StringComparison.Ordinal)).ToList();
var output = paths.Count != 0 ? Path.GetFullPath(paths[0]) : Path.Combine(root, "docs", "content", "reference");
var core = typeof(EasyEcs.World).Assembly.Location;
var xml = Path.ChangeExtension(core, ".xml");
if (!File.Exists(xml)) throw new FileNotFoundException("EasyEcs.Core's XML documentation (GenerateDocumentationFile)", xml);

var reference = MetadataReference.CreateFromFile(core, documentation: new XmlDocs(xml));
var references = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator)
    .Where(p => Path.GetFileName(p) is var name && name.StartsWith("System.", StringComparison.Ordinal) || name is "netstandard.dll" or "Nino.Core.dll")
    .Select(p => (MetadataReference)MetadataReference.CreateFromFile(p));
var compilation = CSharpCompilation.Create("ApiDocs", [], [.. references, reference]);
var assembly = (IAssemblySymbol)compilation.GetAssemblyOrModuleSymbol(reference)!;

var zh = new Translations(Path.Combine(root, "tools", "ApiDocs", "zh"));
var pages = new Reference(compilation, assembly, Language.English, Complexity.Load(root, "api.mdx", "Complexity", "en"), null).Pages();
var costs = Complexity.Load(root, "api.zh.mdx", "复杂度", "zh");
if (costs.Count == 0) costs = Complexity.Load(root, "api.mdx", "Complexity", "zh"); // no Chinese API page: the English table
foreach (var (file, text) in new Reference(compilation, assembly, Language.Chinese, costs, zh).Pages())
    pages.Add(file, text);
Directory.CreateDirectory(output);
foreach (var stale in Directory.EnumerateFiles(output).Where(f => !pages.ContainsKey(Path.GetFileName(f))))
    File.Delete(stale);
foreach (var (file, text) in pages)
{
    var path = Path.Combine(output, file);
    if (!File.Exists(path) || File.ReadAllText(path) != text) File.WriteAllText(path, text);
}

Console.WriteLine($"{pages.Count} files in {Path.GetRelativePath(root, output)}");
if (scaffold) Console.WriteLine($"{zh.Scaffold()} members added to tools/ApiDocs/zh/ to translate");
var problems = zh.Problems();
foreach (var problem in problems) Console.Error.WriteLine(problem);
Console.WriteLine($"{problems.Count} problem(s) in the Chinese reference");
return problems.Count == 0 ? 0 : 1;

static string Root()
{
    for (var dir = new DirectoryInfo(Directory.GetCurrentDirectory()); dir != null; dir = dir.Parent)
        if (File.Exists(Path.Combine(dir.FullName, "EasyEcs.slnx")))
            return dir.FullName;
    throw new InvalidOperationException("Run inside the EasyEcs repository (no EasyEcs.slnx above the current directory)");
}

/// <summary>The reference pages of an assembly's public API in one language.</summary>
internal sealed class Reference
{
    private const string Banner = "{/* Generated by tools/ApiDocs from EasyEcs.Core and its XML documentation: do not edit, run `dotnet run --project tools/ApiDocs`. */}";

    private static readonly SymbolDisplayFormat Signature = new(
        globalNamespaceStyle: SymbolDisplayGlobalNamespaceStyle.Omitted,
        typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypes,
        genericsOptions: SymbolDisplayGenericsOptions.IncludeTypeParameters | SymbolDisplayGenericsOptions.IncludeTypeConstraints |
                         SymbolDisplayGenericsOptions.IncludeVariance,
        memberOptions: SymbolDisplayMemberOptions.IncludeAccessibility | SymbolDisplayMemberOptions.IncludeModifiers |
                       SymbolDisplayMemberOptions.IncludeType | SymbolDisplayMemberOptions.IncludeParameters |
                       SymbolDisplayMemberOptions.IncludeRef | SymbolDisplayMemberOptions.IncludeConstantValue,
        parameterOptions: SymbolDisplayParameterOptions.IncludeType | SymbolDisplayParameterOptions.IncludeName |
                          SymbolDisplayParameterOptions.IncludeDefaultValue | SymbolDisplayParameterOptions.IncludeModifiers |
                          SymbolDisplayParameterOptions.IncludeExtensionThis,
        propertyStyle: SymbolDisplayPropertyStyle.ShowReadWriteDescriptor,
        kindOptions: SymbolDisplayKindOptions.None,
        miscellaneousOptions: SymbolDisplayMiscellaneousOptions.UseSpecialTypes | SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers |
                              SymbolDisplayMiscellaneousOptions.AllowDefaultLiteral);

    private static readonly SymbolDisplayFormat TypeName = new(
        typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypes,
        genericsOptions: SymbolDisplayGenericsOptions.IncludeTypeParameters,
        miscellaneousOptions: SymbolDisplayMiscellaneousOptions.UseSpecialTypes);

    private readonly Dictionary<(string Type, string Member), List<(string Call, string Cost)>> _costs;
    private readonly List<Family> _families;
    private readonly Dictionary<string, string> _links = []; // documentation id to URL
    private readonly Mdx _mdx;

    private readonly Compilation _compilation;
    private readonly Language _lang;
    private readonly Translations? _translations; // null: the English text
    private string Url => _lang.Url;

    public Reference(Compilation compilation, IAssemblySymbol assembly, Language language,
        Dictionary<(string, string), List<(string, string)>> costs, Translations? translations)
    {
        _compilation = compilation;
        _lang = language;
        _translations = translations;
        _costs = costs;
        var types = new List<INamedTypeSymbol>();
        Collect(assembly.GlobalNamespace, types);
        _families = types.GroupBy(t => FamilyName(t)).Select(g => new Family(g.Key, [.. g.OrderBy(t => t.Arity)])).OrderBy(f => f.Name, StringComparer.Ordinal).ToList();
        _mdx = new Mdx(cref => _links.GetValueOrDefault(cref));
        foreach (var family in _families)
        {
            foreach (var type in family.Types) _links[type.GetDocumentationCommentId()!] = Url + family.Slug;
            foreach (var (_, overloads) in Layout(family))
            foreach (var group in overloads)
            foreach (var member in group.Members)
                _links.TryAdd(member.GetDocumentationCommentId() ?? "", Url + family.Slug + "#" + group.Anchor);
            foreach (var type in family.Types.Skip(1)) // the other arities' members link to the first one's
            foreach (var member in Members(type))
                if (_links.GetValueOrDefault(Same(family.First, member)?.GetDocumentationCommentId() ?? "") is { } url)
                    _links.TryAdd(member.GetDocumentationCommentId() ?? "", url);
        }
    }

    private sealed record Overloads(string Anchor, List<ISymbol> Members);

    private readonly Dictionary<Family, List<(string Title, List<Overloads> Groups)>> _layouts = [];

    // The sections of a page: members by kind, overloads with the same documentation together, a unique anchor each.
    private List<(string Title, List<Overloads> Groups)> Layout(Family family)
    {
        if (_layouts.TryGetValue(family, out var layout)) return layout;
        layout = [];
        var used = new HashSet<string>();
        var members = Members(family.First).ToList();
        foreach (var (title, kinds) in Groups)
        {
            var groups = new List<Overloads>();
            // The T1..T9 overloads of one call are one entry (their docs differ only in the count); other overloads
            // share an entry when their docs are the same.
            // (Grouped by the English text, so both languages have the same entries and anchors.)
            foreach (var overloads in members.Where(m => kinds(m)).GroupBy(m => (Name(m), Shape(m) ?? English(m, "summary") + English(m, "remarks"))))
            {
                string anchor = Anchor(overloads.First());
                for (int i = 2; !used.Add(anchor); i++) anchor = Anchor(overloads.First()) + "-" + i;
                groups.Add(new Overloads(anchor, [.. overloads]));
            }

            if (groups.Count != 0) layout.Add((title, groups));
        }

        return _layouts[family] = layout;
    }

    /// <summary>
    /// For an overload generated per component count (type parameters T1..Tn): its shape without them, the same for
    /// every count; null for any other member.
    /// </summary>
    private static string? Shape(ISymbol member)
    {
        if (member is not IMethodSymbol { TypeParameters: [{ Name: "T1" }, ..] } method) return null;
        static bool Numbered(ITypeSymbol t) => t is ITypeParameterSymbol { Name: [ 'T', >= '1' and <= '9' ] };
        return "T1..Tn(" + string.Join(", ", method.Parameters.Where(p => !Numbered(p.Type)).Select(p => p.Type.ToDisplayString())) + ")<" +
               string.Join(", ", method.TypeParameters.Where(t => !Numbered(t)).Select(t => t.Name)) + ">";
    }

    // The overload whose documentation an entry shows: of a T1..Tn group, the two-component one (it reads as the rule).
    private static ISymbol Shown(Overloads group) =>
        Shape(group.Members[0]) != null && group.Members.Count > 1 ? group.Members.FirstOrDefault(m => m is IMethodSymbol { TypeParameters: [_, { Name: "T2" }, ..] }) ?? group.Members[0] : group.Members[0];

    private static ISymbol? Same(INamedTypeSymbol type, ISymbol member) =>
        type.GetMembers(member.Name).FirstOrDefault(m => m.Kind == member.Kind);

    private sealed record Family(string Name, List<INamedTypeSymbol> Types)
    {
        public string Slug => Name.Replace('.', '-').ToLowerInvariant();
        public INamedTypeSymbol First => Types[0];
        /// <summary>A consecutive T1..T9 (or T2..T9) family generated from one template; titled &lt;T1..Tn&gt;, as its types are declared.</summary>
        public bool Arities => Types.Count > 1 && Types[0].Arity > 0 && Types.Select((t, i) => t.Arity == Types[0].Arity + i).All(x => x);

        public string Title => Types.Count == 1 ? First.ToDisplayString(TypeName)
            : Arities ? Name + "<T1..T" + Types[^1].Arity + ">" : string.Join(", ", Types.Select(t => t.ToDisplayString(TypeName)));
    }

    public SortedDictionary<string, string> Pages()
    {
        var pages = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var family in _families)
        {
            if (_translations != null) _translations.Page = family.Slug;
            pages[family.Slug + _lang.Suffix + ".mdx"] = Page(family);
        }

        if (_translations != null) _translations.Page = "index";
        pages["index" + _lang.Suffix + ".mdx"] = Index();
        pages["meta" + _lang.Suffix + ".json"] = $"{{\n  \"title\": \"{_lang.ReferenceTitle}\",\n  \"icon\": \"Library\",\n  \"pages\": [\n    \"index\",\n" +
                                                 string.Join(",\n", _families.Select(f => $"    \"{f.Slug}\"")) + "\n  ]\n}\n";
        return pages;
    }

    private string Index()
    {
        var text = new StringBuilder();
        text.Append("---\ntitle: ").Append(_lang.ReferenceTitle).Append("\ndescription: ").Append(_lang.IndexDescription).Append("\n---\n\n");
        text.Append(Banner).Append("\n\n");
        text.Append(_lang.IndexIntro).Append('\n');
        foreach (var kind in new[] { "Classes", "Structs", "Interfaces", "Enums", "Delegates" })
        {
            var members = _families.Where(f => KindName(f.First) == kind).ToList();
            if (members.Count == 0) continue;
            text.Append("\n## ").Append(_lang.Kinds[kind]).Append(Id(kind)).Append($"\n\n| {_lang.TypeColumn} | {_lang.SummaryColumn} |\n|---|---|\n");
            foreach (var family in members)
                text.Append($"| [{Mdx.Code(family.Title)}]({Url}{family.Slug}) | {Cell(Mdx.Sentence(Doc(family.First, "summary")))} |\n");
        }

        return text.ToString();
    }

    private string Page(Family family)
    {
        var type = family.First;
        var text = new StringBuilder();
        string summary = Doc(type, "summary");
        string kind = type.TypeKind switch
        {
            TypeKind.Interface => "interface",
            TypeKind.Struct => "struct",
            TypeKind.Enum => "enum",
            TypeKind.Delegate => "delegate",
            _ => "class",
        };
        string word = _lang.KindWords[kind];
        text.Append("---\ntitle: ").Append(Yaml(family.Title))
            .Append("\nseoTitle: ").Append(Yaml(_lang.SeoTitle(family.Types.Count > 1 ? family.Name : family.Title, word)))
            .Append("\ndescription: ").Append(Yaml(_lang.Description(Mdx.Sentence(summary), family.Title, word)))
            .Append("\n---\n\n").Append(Banner).Append("\n\n```csharp\n");
        foreach (var t in family.Types) text.Append(Declaration(t)).Append('\n');
        text.Append("```\n\n");
        if (type.ContainingType != null)
            text.Append(_lang.NestedIn(Link(type.ContainingType))).Append("\n\n");
        if (summary.Length != 0) text.Append(summary).Append("\n\n");
        Sections(text, type, "####");
        if (family.Arities)
            text.Append(_lang.Arities(family.Types[0].Arity, family.Types[^1].Arity, Mdx.Code(type.ToDisplayString(TypeName)))).Append("\n\n");

        foreach (var (title, groups) in Layout(family))
        {
            text.Append("## ").Append(_lang.Sections[title]).Append(Id(title)).Append("\n\n");
            foreach (var group in groups) Member(text, type, group);
        }

        return text.ToString().TrimEnd() + "\n";
    }

    private static readonly (string Title, Func<ISymbol, bool> Kind)[] Groups =
    [
        ("Constructors", m => m is IMethodSymbol { MethodKind: MethodKind.Constructor }),
        ("Fields", m => m is IFieldSymbol),
        ("Properties", m => m is IPropertySymbol { IsIndexer: false } && !m.ContainingType.IsExtension), // an extension block's: below
        ("Indexers", m => m is IPropertySymbol { IsIndexer: true } && !m.ContainingType.IsExtension),
        ("Methods", m => m is IMethodSymbol { MethodKind: MethodKind.Ordinary } method && !method.ContainingType.IsExtension),
        ("Extension members", m => m.ContainingType.IsExtension),
        ("Operators", m => m is IMethodSymbol { MethodKind: MethodKind.UserDefinedOperator or MethodKind.Conversion }),
        ("Events", m => m is IEventSymbol),
    ];

    private void Member(StringBuilder text, INamedTypeSymbol type, Overloads group)
    {
        var first = group.Members[0];
        text.Append("### ").Append(Mdx.Code(Name(first))).Append(" [#").Append(group.Anchor).Append("]\n\n```csharp\n");
        foreach (var member in group.Members)
        {
            if (member.ContainingType.IsExtension && member.ContainingType.ExtensionParameter is { } receiver)
                text.Append("extension").Append(TypeParameters(member.ContainingType)).Append('(')
                    .Append(receiver.ToDisplayString(Signature)).Append(") ");
            var signature = member.ToDisplayString(Signature);
            if (member.IsStatic && member.ContainingType.TypeKind == TypeKind.Interface && !signature.Contains("static "))
                signature = (member.IsAbstract ? "static abstract " : "static virtual ") + signature; // not shown for interfaces
            text.Append(signature).Append(member is IFieldSymbol or IMethodSymbol ? ";" : "").Append('\n');
        }

        text.Append("```\n\n");
        var shown = Shown(group);
        if (!SymbolEqualityComparer.Default.Equals(shown, first))
            text.Append(_lang.Overloads(group.Members.Count)).Append("\n\n");
        string summary = Doc(shown, "summary");
        if (summary.Length != 0) text.Append(summary).Append("\n\n");
        Sections(text, shown, "**");

        var rows = _costs.GetValueOrDefault((type.Name, first is IMethodSymbol { MethodKind: MethodKind.Constructor } ? ".ctor" : first.Name));
        if (rows is { Count: > 0 })
        {
            if (rows.Count == 1) text.Append(_lang.ComplexityLabel).Append(rows[0].Cost).Append("\n\n");
            else
            {
                text.Append(_lang.ComplexityLabel.TrimEnd()).Append("\n\n");
                foreach (var (call, cost) in rows) text.Append("- ").Append(call).Append(_lang.Colon).Append(cost).Append('\n');
                text.Append('\n');
            }
        }
    }

    // Type parameters, parameters, returns, remarks and exceptions of a symbol's documentation.
    private void Sections(StringBuilder text, ISymbol symbol, string style)
    {
        var doc = Xml(symbol);
        if (doc == null) return;
        bool heading = style == "####";
        void List(string title, IEnumerable<XElement> items, string attribute)
        {
            var list = items.Select(e => ((string?)e.Attribute(attribute) ?? "", _mdx.Render(e))).Where(p => p.Item2.Length != 0).ToList();
            if (list.Count == 0) return;
            text.Append(heading ? $"#### {_lang.Labels[title]}{Id(title)}\n\n" : $"**{_lang.Labels[title]}**\n\n");
            foreach (var (name, body) in list)
                text.Append("- ").Append(attribute == "cref" ? Link(name) : Mdx.Code(name)).Append(_lang.Colon).Append(body.Replace("\n", "\n  ")).Append('\n');
            text.Append('\n');
        }

        List("Type parameters", doc.Elements("typeparam"), "name");
        List("Parameters", doc.Elements("param"), "name");
        string Label(string title) => heading ? $"#### {_lang.Labels[title]}{Id(title)}\n\n" : _lang.Inline(_lang.Labels[title]);
        if (_mdx.Render(doc.Element("returns")) is { Length: > 0 } returns)
            text.Append(Label("Returns")).Append(returns).Append("\n\n");
        if (_mdx.Render(doc.Element("value")) is { Length: > 0 } value)
            text.Append(Label("Value")).Append(value).Append("\n\n");
        if (_mdx.Render(doc.Element("remarks")) is { Length: > 0 } remarks)
            text.Append(heading ? Label("Remarks") : "").Append(remarks).Append("\n\n");
        List("Exceptions", doc.Elements("exception"), "cref");
    }

    private string Link(string cref) => _links.TryGetValue(cref, out var url) ? $"[{Mdx.Code(Mdx.Label(cref))}]({url})" : Mdx.Code(Mdx.Label(cref));

    private string Link(INamedTypeSymbol type) => Link(type.GetDocumentationCommentId()!);

    private string Doc(ISymbol symbol, string element) => _mdx.Render(Xml(symbol)?.Element(element));

    private string English(ISymbol symbol, string element) => _mdx.Render(Source(symbol).Doc?.Element(element));

    // The documentation a page shows for a symbol, in the page's language (the translation of the English text).
    private XElement? Xml(ISymbol symbol)
    {
        var (id, doc) = Source(symbol);
        return doc == null || _translations == null ? doc : _translations.Lookup(id, doc);
    }

    // The English documentation of a symbol and its documentation id, with <inheritdoc cref="..."/> resolved.
    private (string Id, XElement? Doc) Source(ISymbol symbol)
    {
        var text = symbol.GetDocumentationCommentXml(expandIncludes: true);
        if (string.IsNullOrEmpty(text)) return ("", null);
        var doc = XElement.Parse(text, LoadOptions.PreserveWhitespace);
        if (doc.Element("inheritdoc") is { } inherit && (string?)inherit.Attribute("cref") is { } cref &&
            DocumentationCommentId.GetFirstSymbolForDeclarationId(cref, _compilation) is { } target)
            return Source(target);
        if (!doc.Elements().Any(e => e.Name.LocalName != "inheritdoc")) return ("", null); // <inheritdoc/> of an interface: nothing shown
        return (symbol.GetDocumentationCommentId() ?? "", doc);
    }

    // The explicit id of a heading on a Chinese page (the English heading's own id), so anchors match.
    private string Id(string englishTitle) => _lang.Suffix.Length == 0 ? "" : " [#" + englishTitle.ToLowerInvariant().Replace(' ', '-') + "]";

    private static void Collect(INamespaceSymbol ns, List<INamedTypeSymbol> types)
    {
        foreach (var type in ns.GetTypeMembers()) CollectType(type, types);
        foreach (var inner in ns.GetNamespaceMembers()) Collect(inner, types);
    }

    private static void CollectType(INamedTypeSymbol type, List<INamedTypeSymbol> types)
    {
        if (!Visible(type) || type.IsExtension) return;
        types.Add(type);
        foreach (var nested in type.GetTypeMembers()) CollectType(nested, types);
    }

    private static IEnumerable<ISymbol> Members(INamedTypeSymbol type)
    {
        // A record class's <Clone>$ is public in metadata but unspeakable: no C# code calls it.
        var members = type.GetMembers().Where(m => Visible(m) && !m.IsImplicitlyDeclared && m is not INamedTypeSymbol &&
                                                   !(m is IMethodSymbol { MethodKind: MethodKind.Ordinary, CanBeReferencedByName: false }) &&
                                                   m is not IMethodSymbol { MethodKind: MethodKind.PropertyGet or MethodKind.PropertySet or MethodKind.EventAdd or MethodKind.EventRemove } &&
                                                   !(m is IMethodSymbol { IsStatic: true } impl && type.GetTypeMembers().Any(t => t.IsExtension && t.GetMembers(impl.Name).Length != 0)));
        foreach (var block in type.GetTypeMembers().Where(t => t.IsExtension))
            members = members.Concat(block.GetMembers().Where(m => Visible(m) && m is not IMethodSymbol { MethodKind: MethodKind.PropertyGet or MethodKind.PropertySet }));
        // By name, then by shape: metadata order depends on the order the compiler saw the files in.
        return members.OrderBy(Name, StringComparer.Ordinal).ThenBy(m => m is IMethodSymbol method ? method.TypeParameters.Length : 0)
            .ThenBy(m => m.ToDisplayString(Signature), StringComparer.Ordinal).ToList();
    }

    private static bool Visible(ISymbol symbol) =>
        symbol.DeclaredAccessibility is Accessibility.Public or Accessibility.Protected or Accessibility.ProtectedOrInternal &&
        !symbol.GetAttributes().Any(a => a.AttributeClass?.Name == "EditorBrowsableAttribute" && a.ConstructorArguments is [{ Value: 1 }]) &&
        (symbol.ContainingType == null || Visible(symbol.ContainingType));

    private static string FamilyName(INamedTypeSymbol type) =>
        type.ContainingType == null ? type.Name : FamilyName(type.ContainingType) + "." + type.Name;

    private static string Name(ISymbol member) => member switch
    {
        IMethodSymbol { MethodKind: MethodKind.Constructor } c => c.ContainingType.Name,
        IPropertySymbol { IsIndexer: true } => "this[]",
        IMethodSymbol { MethodKind: MethodKind.UserDefinedOperator or MethodKind.Conversion } op => "operator " + SyntaxFacts.GetText(SyntaxFacts.GetOperatorKind(op.MetadataName)),
        _ => member.Name,
    };

    private static string Anchor(ISymbol member) => Name(member) switch
    {
        "this[]" => "indexer",
        var name when name.StartsWith("operator ", StringComparison.Ordinal) => "op-" + member.MetadataName.Replace("op_", "").ToLowerInvariant(),
        var name => (member is IMethodSymbol { MethodKind: MethodKind.Constructor } ? "ctor" : name.ToLowerInvariant()),
    };

    private static string TypeParameters(INamedTypeSymbol type) => type.TypeParameters.Length == 0 ? "" : "<" + string.Join(", ", type.TypeParameters.Select(t => t.Name)) + ">";

    private static string KindName(INamedTypeSymbol type) => type.TypeKind switch
    {
        TypeKind.Interface => "Interfaces",
        TypeKind.Struct => "Structs",
        TypeKind.Enum => "Enums",
        TypeKind.Delegate => "Delegates",
        _ => "Classes",
    };

    private static string Declaration(INamedTypeSymbol type)
    {
        var text = new StringBuilder("public ");
        if (type.TypeKind == TypeKind.Class && type.IsStatic) text.Append("static ");
        else if (type.TypeKind == TypeKind.Class && type.IsAbstract) text.Append("abstract ");
        else if (type.TypeKind == TypeKind.Class && type.IsSealed) text.Append("sealed ");
        if (type.TypeKind == TypeKind.Struct && type.IsReadOnly) text.Append("readonly ");
        if (type.IsRefLikeType) text.Append("ref ");
        if (type.TypeKind == TypeKind.Delegate && type.DelegateInvokeMethod is { } invoke)
            return text.Append("delegate ").Append(invoke.ReturnsByRef ? "ref " : "").Append(invoke.ReturnType.ToDisplayString(TypeName)).Append(' ')
                .Append(type.ToDisplayString(TypeName).Split('.')[^1]).Append('(')
                .Append(string.Join(", ", invoke.Parameters.Select(p => p.ToDisplayString(Signature)))).Append(");").ToString();
        text.Append(type.TypeKind switch
        {
            TypeKind.Interface => "interface ",
            TypeKind.Struct => type.IsRecord ? "record struct " : "struct ",
            TypeKind.Enum => "enum ",
            _ => type.IsRecord ? "record " : "class ",
        });
        text.Append(type.ToDisplayString(new SymbolDisplayFormat(genericsOptions: SymbolDisplayGenericsOptions.IncludeTypeParameters | SymbolDisplayGenericsOptions.IncludeVariance)));
        var bases = new List<string>();
        if (type.TypeKind == TypeKind.Class && type.BaseType is { SpecialType: not SpecialType.System_Object } baseType) bases.Add(baseType.ToDisplayString(TypeName));
        if (type.TypeKind == TypeKind.Enum && type.EnumUnderlyingType is { SpecialType: not SpecialType.System_Int32 } underlying) bases.Add(underlying.ToDisplayString(TypeName));
        bases.AddRange(type.Interfaces.Where(i => Visible(i) || i.ContainingNamespace?.ToDisplayString().StartsWith("System", StringComparison.Ordinal) == true).Select(i => i.ToDisplayString(TypeName)));
        if (bases.Count != 0) text.Append(" : ").Append(string.Join(", ", bases));
        foreach (var parameter in type.TypeParameters)
        {
            var constraints = new List<string>();
            if (parameter.HasUnmanagedTypeConstraint) constraints.Add("unmanaged");
            else if (parameter.HasValueTypeConstraint) constraints.Add("struct");
            if (parameter.HasReferenceTypeConstraint) constraints.Add("class");
            constraints.AddRange(parameter.ConstraintTypes.Select(c => c.ToDisplayString(TypeName)));
            if (parameter.HasConstructorConstraint && !parameter.HasValueTypeConstraint) constraints.Add("new()");
            if (parameter.AllowsRefLikeType) constraints.Add("allows ref struct");
            if (constraints.Count != 0) text.Append(" where ").Append(parameter.Name).Append(" : ").Append(string.Join(", ", constraints));
        }

        return text.ToString();
    }

    private static string Cell(string text) => Mdx.Escape(text).Replace("|", "\\|");

    private static string Yaml(string text) => "\"" + text.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
